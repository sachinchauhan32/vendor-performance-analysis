FROM sales
GROUP BY vendorname;

-- ===================================================== Running Total of Daily Sales


SELECT salesdate, ROUND(SUM(salesdollars),2) AS daily_sales,
ROUND(SUM(SUM(salesdollars))OVER( ORDER BY salesdate),2) AS running_total
FROM sales
GROUP BY salesdate
ORDER BY salesdate;


-- =====================================================Previous Day Sales using LAG()


SELECT salesdate, ROUND(SUM(salesdollars),2) AS daily_sales,
LAG(ROUND(SUM(salesdollars),2)) OVER (ORDER BY salesdate)
AS previous_day_sales
FROM sales
GROUP BY salesdate
ORDER BY salesdate;



-- ===================================================== Daily Growth compared to Previous Day


SELECT salesdate, ROUND(SUM(salesdollars),2) AS daily_sales,
ROUND(SUM(salesdollars) - LAG(SUM(salesdollars)) OVER(ORDER BY salesdate),2) AS growth
FROM sales
GROUP BY salesdate
ORDER BY salesdate;


--=====================================================Next Day Sales using LEAD()


SELECT salesdate, ROUND(SUM(salesdollars),2) AS daily_sales,
LEAD(ROUND(SUM(salesdollars),2)) OVER( ORDER BY salesdate ) AS next_day_sales
FROM sales
GROUP BY salesdate
ORDER BY salesdate;



---===================================================== 7-Day Moving Average of Daily Sales

SELECT salesdate, ROUND(SUM(salesdollars),2) AS daily_sales,
ROUND(AVG(SUM(salesdollars)) OVER(ORDER BY salesdate ROWS BETWEEN 6 PRECEDING AND CURRENT ROW),2) AS moving_average
FROM sales
GROUP BY salesdate
ORDER BY salesdate;


