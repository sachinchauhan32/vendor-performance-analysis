WITH VendorSales AS (
    SELECT 
        vendorname,
        SUM(salesdollars) AS total_sales
    FROM sales
    GROUP BY vendorname
)
SELECT 
    vendorname,
    ROUND(total_sales, 2) AS total_sales
FROM VendorSales
WHERE total_sales > (SELECT AVG(total_sales) FROM VendorSales)
ORDER BY total_sales DESC;



---====================================================Vendors whose Sales are Below Average

WITH VendorSales AS (
    SELECT 
        vendorname,
        SUM(salesdollars) AS total_sales
    FROM sales
    GROUP BY vendorname
)
SELECT 
    vendorname,
    ROUND(total_sales, 2) AS total_sales
FROM VendorSales
WHERE total_sales < (SELECT AVG(total_sales) FROM VendorSales)
ORDER BY total_sales DESC;


